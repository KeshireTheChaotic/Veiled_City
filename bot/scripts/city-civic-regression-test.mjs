/** Civic interdependency scenarios: bounded outage, repairs, layered claims, routes/proxies, social transmission and long history. */
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { performance } from "node:perf_hooks";
import { VeiledDB } from "../src/db.js";
import { indexWorldEvent } from "../src/city-calendar.js";
import { updateCityCore, submitInstitutionAction, configureCityFlags, runInstitutionDirector } from "../src/city-core.js";
import { updateCityCivic, connectCity, changeCityService, reviewCivicChange, transmitCityBelief, historyContext } from "../src/city-civic.js";
import { assertNpcAvailability, npcAvailability } from "../src/city-constraints.js";
import { configureSimulationEntity, submitNpcAction } from "../src/simulation.js";

const temp=fs.mkdtempSync(path.join(os.tmpdir(),"vc-city-civic-"));
const db=new VeiledDB(path.join(temp,"test.sqlite"),path.resolve("sql/schema.sql"));
const guild="civic-dependencies",start=performance.now();
try{
  db.ensureCampaign(guild);db.ensureCampaign("other");
  indexWorldEvent(db,guild,{key:"source",title:"Established civic fixture",source_kind:"gm",source_id:"GM notes",truth_status:"observed"});
  const core=(kind,key,data)=>updateCityCore(db,guild,{kind,key,source_event:"source",data});
  const civic=(kind,key,data)=>updateCityCivic(db,guild,{kind,key,source_event:"source",data});
  const connect=(kind,from,to,extra={})=>connectCity(db,guild,{kind,from,to,source_event:"source",...extra});
  core("district","north",{name:"North",indices:{safety:50}});
  core("district","south",{name:"South",indices:{safety:50}});
  core("institution","utility",{name:"Utility",mandate:"Maintain services",jurisdictions:["north"],procedures:["document_request"],capacity:4});
  for(const key of ["pump","hospital","other-site"]) configureSimulationEntity(db,guild,"location",key,{});
  const infra=(key,locations)=>civic("infrastructure",key,{name:key,service:"water",native_condition:100,operator:"utility",locations,repair_requirements:["Technician"]});
  infra("upstream",["pump"]);infra("downstream",["hospital"]);infra("unrelated",["other-site"]);
  connect("infrastructure","upstream","downstream");
  assert.throws(()=>connect("infrastructure","downstream","upstream"),/cycle/);
  const pending=changeCityService(db,guild,{key:"upstream",condition:0,source_event:"source"});
  assert.equal(pending.status,"pending");
  assert.equal(db.getCityRecord(guild,"infrastructure","upstream").data.native_condition,100);
  reviewCivicChange(db,guild,{key:pending.record_key,decision:"approve"},"gm");
  assert.equal(db.getCityRecord(guild,"infrastructure","downstream").data.effective_condition,0);
  assert.equal(db.getCityRecord(guild,"infrastructure","unrelated").data.effective_condition,100);
  assert.equal(db.getSimulationEntity(guild,"location","hospital").state.civic_services.downstream.condition,0);
  changeCityService(db,guild,{key:"upstream",condition:100,source_event:"source"});
  assert.equal(db.getCityRecord(guild,"infrastructure","downstream").data.effective_condition,100);
  for(const [key,type,domain] of [["deed","deed","mundane"],["lease","lease","mundane"],["threshold","threshold","metaphysical"]]){
    civic("property",key,{location:"hospital",claim_type:type,claimant:key,terms:"Separately established terms",validity:"disputed",domain,established_terms:true});
  }
  assert.equal(db.listCityRecords(guild,{kind:"property",includeGM:true}).length,3);
  db.upsertNpcProfile(guild,{npcKey:"technician",displayName:"Technician",activityTier:"active"});
  db.upsertNpcGoal(guild,{npcKey:"technician",goalKey:"repair",objective:"Maintain the pump",priority:80});
  configureSimulationEntity(db,guild,"npc","technician",{activity_tier:"active",location_key:"pump"});
  civic("routine","technician-routine",{npc:"technician",residence:"pump",occupation:"Technician",intervals:[{start:0,end:480,location:"pump"}],projects:["Maintain pump"]});
  connect("route","pump","hospital",{duration:30});
  assert.throws(()=>assertNpcAvailability(db,guild,"technician",{type:"travel",location_key:"hospital",delay_minutes:0}),/route duration/);
  assert.equal(npcAvailability(db,guild,"technician").preferences.length,1);
  assert.equal(db.getSimulationEntity(guild,"npc","technician").state.location_key,"pump","routines do not teleport actors");
  changeCityService(db,guild,{key:"upstream",condition:90,source_event:"source"});
  submitNpcAction(db,guild,{actor_type:"npc",actor_key:"technician",type:"repair",goal_key:"repair",location_key:"pump",significance:"routine"},{roll:()=>20});
  assert.equal(db.getCityRecord(guild,"infrastructure","upstream").data.native_condition,100,"existing NPC repair action restores linked service");
  const session=db.startSession(guild,"Proxy test","already_together");
  db.upsertNpcProxy(guild,session.id,{npcName:"Technician",userId:"proxy",status:"active"});
  assert.throws(()=>assertNpcAvailability(db,guild,"technician",{type:"prepare"}),/proxy/);
  const proxy=db.listNpcProxies(session.id)[0];db.releaseNpcProxy(proxy.id);
  civic("community","tenants",{name:"Tenant association",capacity:3,members:["technician"],priorities:["Reliable water"],shared_history:[],district:"north"});
  db.upsertNpcKnowledge(guild,{npcKey:"technician",knowledgeKey:"anomaly",content:"I saw an unexplained pulse at the pump.",beliefState:"suspected",confidence:80});
  connect("channel","npc:technician","community:tenants");
  connect("channel","community:tenants","institution:utility");
  connect("channel","institution:utility","audience:news-readers");
  const transmit=(key,from_type,from_key,to_type,to_key,information_key)=>transmitCityBelief(db,guild,{key,source_event:"source",from_type,from_key,to_type,to_key,information_key,mechanism:"authorized_report",authorized:true,distortion:5});
  transmit("hop-1","npc","technician","community","tenants","anomaly");
  transmit("hop-2","community","tenants","institution","utility","hop-1");
  const third=transmit("hop-3","institution","utility","audience","news-readers","hop-2");
  assert.equal(third.data.origin,"npc:technician");assert.equal(third.data.confidence,65);assert.equal(third.data.distortion,15);
  assert.equal(transmit("hop-3","institution","utility","audience","news-readers","hop-2").data.confidence,65);
  assert.equal(db.listCanon(guild,{includeGM:true}).length,0,"repetition does not create truth");
  assert.throws(()=>transmit("leak","npc","technician","community","tenants","private-global-secret"),/does not know/);
  civic("identity","observer-alias",{alias:"Night Warden",subject_type:"npc",subject_key:"technician",observer_type:"institution",observer:"utility",information_key:"hop-2"});
  assert.equal(db.listCityRecords("other",{kind:"identity",includeGM:true}).length,0);
  civic("reputation","utility-rep",{observer_type:"institution",observer:"utility",identity:"Night Warden",dimensions:{trust:3,suspicion:-1}});
  civic("reputation","tenants-rep",{observer_type:"community",observer:"tenants",identity:"Night Warden",dimensions:{fear:2,trust:-2}});
  assert(db.listSimulationEntities(guild,"relationship").length>=2);
  civic("weather","storm",{district:"north",start:100,end:200,description:"A forecast storm",environment_key:"Occult Crime Scene"});
  assert.throws(()=>civic("weather","damage",{district:"north",start:100,end:200,description:"Rain",pc_damage:3}),/player mechanics|damage/);
  const catastrophe=civic("weather","superstorm",{district:"north",start:100,end:200,description:"Supernatural storm proposal",supernatural_disaster:true});
  assert.equal(catastrophe.status,"pending");assert.equal(db.getCityRecord(guild,"weather","superstorm"),null);
  reviewCivicChange(db,guild,{key:catastrophe.record_key,decision:"reject"},"gm");
  civic("personnel","clerk",{institution:"utility",npc:"technician",role:"Records clerk",capacity:2,actions:["document_request"],dissent_actions:["document_request"]});
  core("institution","utility",{personnel:["clerk"]});
  assert.throws(()=>submitInstitutionAction(db,guild,{key:"dissent",institution:"utility",type:"document_request",jurisdiction:"north",source_event:"source",personnel_key:"clerk"}),/dissent/);
  civic("personnel","clerk",{dissent_actions:[]});
  submitInstitutionAction(db,guild,{key:"authorized",institution:"utility",type:"document_request",jurisdiction:"north",source_event:"source",personnel_key:"clerk"});
  configureCityFlags(db,guild,{institutions:true});runInstitutionDirector(db,guild,"delegation");
  assert.equal(db.getCityRecord(guild,"personnel","clerk").data.capacity,1);
  civic("history","old-flood",{title:"Earlier flood warning",summary:"Flood warnings and differing interpretations were recorded.",source_events:["source"],preserves_contradictions:true});
  for(let i=0;i<110;i++) civic("history",`noise-${i}`,{title:`Routine history ${i}`,summary:"Unrelated mundane history.",source_events:["source"],preserves_contradictions:true});
  const history=historyContext(db,guild,"flood");assert.equal(history[0].summary.title,"Earlier flood warning");
  assert.equal(history[0].sources[0].event_key,"source");assert(JSON.stringify(history).length<=10000);
  assert.equal(db.getCampaign(guild).veil_exposure,0);assert.equal(db.getCampaign(guild).fear,0);
  const backup=db.createBackup(guild);db.restoreBackup(guild,backup.id);
  assert.equal(db.getCityRecord(guild,"infrastructure","downstream").data.effective_condition,100);
  assert.equal(db.cityEdges(guild,"channel").length,3);
  console.log(`Civic interdependency regressions PASS; ${(performance.now()-start).toFixed(1)}ms; connected-service budget 20; history <=10000 chars; 0 extra model calls.`);
}finally{db.close();fs.rmSync(temp,{recursive:true,force:true});}
